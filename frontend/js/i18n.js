  function detectLanguage() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'en' || saved === 'zh-CN') return saved;
    } catch (_) {}
    return (navigator.language || '').toLowerCase().indexOf('en') === 0 ? 'en' : 'zh-CN';
  }

  var language = detectLanguage();

  function t(key, chineseFallback) {
    return language === 'en' && messages[key] ? messages[key] : chineseFallback;
  }

  function rasterMetadata(value, kind) {
    var key = null;
    var processingKeys = {
      '坡度(Slope)': 'raster.processing-slope',
      '坡向(Aspect)': 'raster.processing-aspect',
      '山体阴影(Hillshade)': 'raster.processing-hillshade',
    };
    var unitKeys = {
      '°（角度）': 'raster.unit-degree-value',
      '0–255（相对亮度）': 'raster.unit-relative-brightness',
      '无量纲（-1 至 1）': 'raster.unit-dimensionless-range',
      '未推导（取决于表达式与输入单位）': 'raster.unit-not-derived',
    };
    if (language !== 'en') return value;
    if (kind === 'processing') key = processingKeys[String(value || '')];
    else if (kind === 'value_units') key = unitKeys[String(value || '')];
    return key ? (messages[key] || value) : value;
  }

  function translate(root) {
    if (!root || !root.querySelectorAll) return;
    var nodes = [];
    if (root.matches && root.matches('[data-i18n]')) nodes.push(root);
    nodes = nodes.concat(Array.prototype.slice.call(root.querySelectorAll('[data-i18n]')));
    nodes.forEach(function(node) {
      if (!node.hasAttribute('data-i18n-zh')) node.setAttribute('data-i18n-zh', node.textContent);
      node.textContent = language === 'en' ? (messages[node.dataset.i18n] || node.dataset.i18nZh) : node.dataset.i18nZh;
    });

    ['title', 'placeholder', 'aria-label'].forEach(function(attr) {
      var keyAttr = 'data-i18n-' + attr.replace('-', '-');
      var selector = '[' + keyAttr + ']';
      var attrNodes = [];
      if (root.matches && root.matches(selector)) attrNodes.push(root);
      attrNodes = attrNodes.concat(Array.prototype.slice.call(root.querySelectorAll(selector)));
      attrNodes.forEach(function(node) {
        var sourceAttr = 'data-i18n-zh-' + attr;
        if (!node.hasAttribute(sourceAttr)) node.setAttribute(sourceAttr, node.getAttribute(attr) || '');
        var key = node.getAttribute(keyAttr);
        node.setAttribute(attr, language === 'en' ? (messages[key] || node.getAttribute(sourceAttr)) : node.getAttribute(sourceAttr));
      });
    });
  }

  function setLanguage(next) {
    if (next !== 'en' && next !== 'zh-CN') return;
    language = next;
    try { localStorage.setItem(STORAGE_KEY, language); } catch (_) {}
    document.documentElement.lang = language;
    translate(document);
    var selector = document.getElementById('uiLanguageSelect');
    if (selector) selector.value = language;
    document.dispatchEvent(new CustomEvent('gis:languagechange', { detail: { language: language } }));
  }

  function layerLabel(name) {
    name = String(name || '');
    if (language !== 'en') return name;
    var labels = {
      '样例_多边形地块': 'Sample polygons',
      '样例_POI实心点': 'Sample POIs',
      '样例_道路路网': 'Sample road network'
    };
    if (labels[name]) return labels[name];
    var buffer = name.match(/^(.+)_缓冲区(?:_\d+_\d+)?$/);
    if (buffer) return layerLabel(buffer[1]) + ' buffer';
    return name;
  }

  GIS.i18n = {
    t: t,
    rasterMetadata: rasterMetadata,
    getLanguage: function() { return language; },
    setLanguage: setLanguage,
    translate: translate,
    layerCount: function(count) { return language === 'en' ? count + (count === 1 ? ' layer' : ' layers') : count + ' 个图层'; },
    featureCount: function(count) { return language === 'en' ? '· ' + count + (count === 1 ? ' feature' : ' features') : '· ' + count + ' 个要素'; },
    isEnglish: function() { return language === 'en'; },
    layerLabel: layerLabel
  };

  document.documentElement.lang = language;
  translate(document);
  if (document.readyState === 'complete') translate(document);
  else window.addEventListener('load', function() { translate(document); }, { once: true });
  var languageSelect = document.getElementById('uiLanguageSelect');
  if (languageSelect) {
    languageSelect.value = language;
    languageSelect.addEventListener('change', function() { setLanguage(languageSelect.value); });
  }
